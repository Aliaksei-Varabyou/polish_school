// What the rendered content covers, in the shape the web needs: which paragraphs have tasks (and how
// many), and which paragraphs a tag reaches. Written to curriculum/coverage.generated.ts by
// scripts/genCoverage.ts, because the browser cannot render templates itself (node:crypto).
import { PARAGRAPHS } from "../curriculum/books.ts";
import { TAGS } from "../curriculum/tags.ts";
import type { Content } from "./content.ts";

export interface Coverage {
  /** tasks per language, by paragraph id, in textbook order; paragraphs without tasks are absent */
  paragraphTasks: Record<string, number>;
  /** paragraphs holding at least one task with the tag, in textbook order */
  tagParagraphs: Record<string, string[]>;
}

export function computeCoverage({ tasks }: Content): Coverage {
  // languages are rendered symmetrically (a substitution is kept only if it verifies in all of
  // them), so one language's count is every language's count — a test holds that
  const polish = tasks.filter((t) => t.lang === "pl").map((t) => t.task);

  const paragraphTasks: Record<string, number> = {};
  for (const p of PARAGRAPHS) {
    const n = polish.filter((t) => t.topicId === p.id).length;
    if (n > 0) paragraphTasks[p.id] = n;
  }

  const tagParagraphs: Record<string, string[]> = {};
  for (const tag of TAGS) {
    tagParagraphs[tag.id] = PARAGRAPHS.filter((p) => polish.some((t) => t.topicId === p.id && t.tags?.includes(tag.id))).map((p) => p.id);
  }
  return { paragraphTasks, tagParagraphs };
}

/** The generated module's source. Deterministic, so a test can compare it with the file byte for byte. */
export function coverageModule({ paragraphTasks, tagParagraphs }: Coverage): string {
  const entries = (o: object) =>
    Object.entries(o)
      .map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`)
      .join("\n");
  return `// Generated by \`npm run gen:coverage -w @portal/trainer-history\` — do not edit by hand.
// How much rendered content each paragraph holds; the web cannot render templates itself.

/** tasks per language, by paragraph id; a paragraph that is absent has none */
export const PARAGRAPH_TASKS: Record<string, number> = {
${entries(paragraphTasks)}
};

/** paragraphs holding at least one task with the tag, by tag id */
export const TAG_PARAGRAPHS: Record<string, string[]> = {
${entries(tagParagraphs)}
};
`;
}
